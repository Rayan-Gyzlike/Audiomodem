"""Константы модема: параметры аудиосигнала и протокола кадра.

Формат кадра (расширенный с CRC32):

    [ PREAMBLE (32 бита) ][ SYNC_WORD (16 бит) ][ LEN (8 бит) ]
    [ DATA (LEN байт) ][ CRC32 (4 байта) ]

CRC32 добавляется к полезной нагрузке ДО кодирования Рида-Соломона,
что позволяет на приёме проверить целостность раскодированных данных.
"""

# ─── Параметры аудиосигнала ───────────────────────────────────────────────────

SAMPLE_RATE = 44100  # Частота дискретизации (Гц)

# FSK (Frequency Shift Keying) — классические AFSK-подобные частоты.
# Бит "0" кодируется тоном 1200 Гц, бит "1" — тоном 2200 Гц.
FREQ_ZERO = 1200.0  # Гц — символ "0"
FREQ_ONE = 2200.0   # Гц — символ "1"

BAUD_RATE = 100  # Символов (бит) в секунду
SAMPLES_PER_SYMBOL = SAMPLE_RATE // BAUD_RATE  # = 441 сэмпл на бит

# Регулируемая амплитуда сигнала (0.0 - 1.0).
# Для стресс-тестов на разной дистанции / шуме:
#   Тест 1 (базовый, 30см): 0.5 — умеренная громкость
#   Тест 2 (средняя дист.): 0.7 — стандартная
#   Тест 3 (макс. дальность): 1.0 — максимум
#   Тест 4 (шумная среда): 0.85 — повышенная для борьбы с шумом
AMPLITUDE = 0.7  # Амплитуда сигнала (0.0 - 1.0)

# ─── Параметры кадра ──────────────────────────────────────────────────────────

# Преамбула: чередование бит 0/1 для восстановления тактовой частоты приёмником.
PREAMBLE_BITS = [0, 1] * 16  # 32 бита

# Синхрослово (уникальный маркер начала кадра), выбрано так, чтобы не совпадать
# с чередующимся паттерном преамбулы. Длина — 2 байта (16 бит).
SYNC_WORD_BYTES = bytes([0x2D, 0xD4])

# ─── Защита ошибок ────────────────────────────────────────────────────────────

# Число байт избыточности Рида-Соломона (позволяет исправить до RS_NSYM // 2
# повреждённых байт в закодированном сообщении).
RS_NSYM = 10

# Размер CRC32 в байтах (4 байта = 32 бита, полином 0xEDB88320).
CRC_SIZE_BYTES = 4

# Максимальная длина закодированного (с RS) сообщения в байтах.
# Ограничение диктуется тем, что длина передаётся одним байтом (0-255).
MAX_ENCODED_LEN = 255

# ─── Повторная передача (Repeat TX) ──────────────────────────────────────────

# Сколько раз каждый кадр отправляется повторно для повышения надёжности.
# Пауза между повторами — ~0.3 сек (определяется скоростью воспроизведения WAV).
TRANSMIT_REPEATS = 1  # ARQ управляет повторами: 1 кадр → ожидание ACK/NACK → повтор при таймауте

# ─── Дедупликация ─────────────────────────────────────────────────────────────

# Время (в секундах), в течение которого повторное получение того же сообщения
# (с совпадающим CRC32) считается дубликатом и отбрасывается.
DEDUP_WINDOW_SECONDS = 3.0

# ─── ARQ (Automatic Repeat reQuest) ──────────────────────────────────────────
# Протокол подтверждения приёма: передатчик отправляет данные, ждёт ответный
# ACK/NACK от приёмника и повторяет кадр при неудаче.

# Укороченная преамбула контрольного кадра (8 бит вместо 32 бит данных)
CONTROL_PREAMBLE_BITS = [0, 1] * 4  # 8 бит — ~0.07 сек

# Байты-идентификаторы контрольных кадров
CONTROL_BYTE_ACK = 0x06   # Подтверждение приёма (ASCII ACK)
CONTROL_BYTE_NACK = 0x15  # Запрос повтора (ASCII NACK)

# Таймаут ожидания ACK/NACK перед повторной отправкой (секунды).
# Увеличен до 5.0 сек, чтобы приёмник успел декодировать кадр и отправить ACK
# до того, как передатчик начнёт повторную отправку.
ARQ_TIMEOUT_SECONDS = 5.0

# Максимальное число повторных отправок (включая первую)
MAX_RETRIES = 3

# Защита от собственного эха: микрофон игнорируется после передачи + 600 мс
# (600мс на затухание эха в помещении + опустошение системных буферов)
BLANKING_MS = 600
BLANKING_SECONDS = BLANKING_MS / 1000.0

# ─── Асинхронный декодинг и таймауты ──────────────────────────────────────────

# Таймаут на декодирование одного чанка (сек). Если превышен — сброс состояния.
DECODE_TIMEOUT_SECONDS = 2.0

# Максимальный размер очереди аудио-чанков. При переполнении старые дропаются.
AUDIO_QUEUE_MAXSIZE = 20

# Тишина перед NACK (мс) — чтобы звуковая карта Windows успела проснуться
# и не срезала первые миллисекунды тона.
NACK_SILENCE_MS = 100
NACK_SILENCE_SAMPLES = int(SAMPLE_RATE * NACK_SILENCE_MS / 1000)

# ─── Фрагментация файлов ──────────────────────────────────────────────────────
# Файлы > FILE_CHUNK_RAW_MAX байт автоматически разбиваются на чанки.
# Формат чанка: "F:<filename>:<total>:<index>:<base64_data>"
# where total = общее число чанков, index = номер (0-based).

FILE_CHUNK_RAW_MAX = 128  # Макс. размер сырых данных в одном чанке (байт)
# Base64 увеличивает размер в ~1.33 раза + заголовок ~40 символов.
# Итого ~220 символов — вписывается в MAX_ENCODED_LEN=255.

# ─── ARQ: таймауты и повторы ─────────────────────────────────────────────────
# Задержка перед отправкой ACK/NACK (мс) — чтобы передатчик успел
# сбросить IS_TRANSMITTING и переключиться в режим прослушки микрофона.
ACK_SEND_DELAY_MS = 100  # 100мс — достаточно для сброса TX-флага на фронтенде

# ─── Защита от коллизий (мультиплеер) ────────────────────────────────────────
# Сессия определяет частотный сдвиг для разных пар устройств.
# Каждая сессия сдвигает FREQ_ZERO и FREQ_ONE на SESSION_ID * FREQUENCY_STEP_HZ.
# До 4 пар устройств (SESSION_ID 0-3) работают на разных "частотных каналах".
SESSION_ID = 0  # Номер сессии (0-3), устанавливается через /api/session
FREQUENCY_STEP_HZ = 250.0  # Шаг частотного сдвига между сессиями

# Backoff перед передачей (мс) — случайная задержка для избежания коллизий
COLLISION_BACKOFF_BASE_MS = 100  # Базовый случайный backoff (мс)
COLLISION_BACKOFF_MAX_MS = 500   # Максимальный backoff (мс)

# ─── Профили стресс-тестов ───────────────────────────────────────────────────
# Предустановленные конфигурации для каждого тест-кейса.
# Активируются через API /api/test-profile
TEST_PROFILES = {
    "basic": {"amplitude": 0.5, "transmit_repeats": 2, "description": "Тест 1: базовый, 30см, тишина"},
    "medium": {"amplitude": 0.7, "transmit_repeats": 3, "description": "Тест 2: средняя дистанция"},
    "max_range": {"amplitude": 1.0, "transmit_repeats": 4, "description": "Тест 3: максимальная дальность"},
    "noisy": {"amplitude": 0.85, "transmit_repeats": 4, "description": "Тест 4: шумная среда"},
    "multiplayer": {"amplitude": 0.6, "transmit_repeats": 2, "description": "Тест 5: мультиплеер / коллизии"},
}
